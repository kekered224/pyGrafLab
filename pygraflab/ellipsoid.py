"""
Ellipsoidal harmonic coefficients (CEl) and normal gravity computation
via the Somigliana-Pizzetti closed-form formula.

Ported from GrafLab 2.1.4 (lines 2371-2376, 4303-4329).
"""

import numpy as np
from .coords import ell2cart


def compute_ellipsoid_coefficients(ellipsoid, R, GM_ggm):
    """Compute even zonal spherical harmonic coefficients of the normal gravity
    field generated by the reference ellipsoid.

    Parameters
    ----------
    ellipsoid : dict – from constants.get_ellipsoid()
    R         : float – reference sphere radius of the GGM [m]
    GM_ggm    : float – GM of the GGM [m^3 s^-2]

    Returns
    -------
    CEl : ndarray of shape (21,)
        CEl[2n] = fully-normalised C_{2n,0} for n = 0..10.
        Odd indices are zero.
    """
    a = ellipsoid['a']
    e = ellipsoid['e']
    omega = ellipsoid['omega']
    C20 = ellipsoid['C20']
    GM_el = ellipsoid['GM']

    CEl = np.zeros(21)
    for n in range(11):  # n = 0, 1, ..., 10  ->  degrees 0, 2, ..., 20
        deg = 2 * n
        val = (
            ((-1)**n * 3.0 * e**(2 * n))
            / ((2 * n + 1) * (2 * n + 3) * np.sqrt(4 * n + 1))
            * (1.0 - n - 5.0**1.5 * n * C20 / e**2)
            * (a / R)**deg
            * (GM_el / GM_ggm)
        )
        CEl[deg] = val
    return CEl


def normal_gravity(lat_ell, h, ellipsoid):
    """Compute normal gravity using the Somigliana-Pizzetti formula.

    Parameters
    ----------
    lat_ell   : float or ndarray – geodetic (ellipsoidal) latitude [rad]
    h         : float or ndarray – ellipsoidal height [m]
    ellipsoid : dict

    Returns
    -------
    gammaP : ndarray – magnitude of normal gravity [m s^-2]
    """
    a = ellipsoid['a']
    e = ellipsoid['e']
    GM_el = ellipsoid['GM']
    omega = ellipsoid['omega']

    b = a * np.sqrt(1.0 - e**2)            # semi-minor axis
    E = np.sqrt(a**2 - b**2)                # linear eccentricity
    E2 = E**2

    # Cartesian coordinates of the computation point
    fi = np.atleast_1d(np.asarray(lat_ell, dtype=float))
    hh = np.atleast_1d(np.asarray(h, dtype=float))
    lam = np.zeros_like(fi)
    X, Y, Z = ell2cart(fi, lam, hh, ellipsoid)

    # Ellipsoidal harmonic coordinates (u, beta)
    r2 = X**2 + Y**2 + Z**2
    disc = r2 - E2
    u = np.sqrt(disc * (0.5 + 0.5 * np.sqrt(1.0 + 4.0 * E2 * Z**2 / disc**2)))
    beta = np.arctan2(Z * np.sqrt(u**2 + E2), u * np.sqrt(X**2 + Y**2))

    # Weight factor
    sin_b = np.sin(beta)
    cos_b = np.cos(beta)
    w = np.sqrt((u**2 + E2 * sin_b**2) / (u**2 + E2))

    # Somigliana auxiliary functions
    q = 0.5 * ((1.0 + 3.0 * u**2 / E2) * np.arctan(E / u) - 3.0 * u / E)
    q_prime = 3.0 * (1.0 + u**2 / E2) * (1.0 - u / E * np.arctan(E / u)) - 1.0
    q0 = 0.5 * ((1.0 + 3.0 * b**2 / E2) * np.arctan(E / b) - 3.0 * b / E)

    # Normal gravity components in (u, beta) system
    gamma_u = -1.0 / w * (
        GM_el / (u**2 + E2)
        + omega**2 * a**2 * E / (u**2 + E2) * (q_prime / q0)
        * (0.5 * sin_b**2 - 1.0 / 6.0)
        - omega**2 * u * cos_b**2
    )
    gamma_beta = -1.0 / w * (
        -omega**2 * a**2 * q / (np.sqrt(u**2 + E2) * q0)
        + omega**2 * np.sqrt(u**2 + E2)
    ) * sin_b * cos_b

    gammaP = np.sqrt(gamma_u**2 + gamma_beta**2)
    return gammaP
